// checkSync 内存产物与仓内 gen/ts 逐字节对账,并检测残留文件
func checkSync(files map[string]string) error {
	committed := map[string]bool{}
	entries, err := os.ReadDir(outputDir)
	if err != nil {
		return fmt.Errorf("读取 %s: %w（先运行 go run ./cmd/gen-ts 生成）", outputDir, err)
	}
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".d.ts") {
			committed[e.Name()] = true
		}
	}
	for rel, content := range files {
		b, err := os.ReadFile(filepath.Join(outputDir, rel))
		if err != nil {
			return fmt.Errorf("%s 缺失: 先运行 `go run ./cmd/gen-ts` 更新后提交", rel)
		}
		if string(b) != content {
			return fmt.Errorf("%s 与 idl/ 不同步,请运行 `go run ./cmd/gen-ts` 更新后提交", rel)
		}
		delete(committed, rel)
	}
	if len(committed) > 0 {
		left := make([]string, 0, len(committed))
		for name := range committed {
			left = append(left, outputDir+"/"+name)
		}
		sort.Strings(left)
		return fmt.Errorf("残留产物(IDL 已不含对应类型): %s,请运行 `go run ./cmd/gen-ts` 后删除", strings.Join(left, ", "))
	}
	return nil
}

func writeAll(files map[string]string) error {
	if err := os.MkdirAll(outputDir, 0o755); err != nil {
		return fmt.Errorf("创建输出目录: %w", err)
	}
	names := make([]string, 0, len(files))
	for rel := range files {
		names = append(names, rel)
	}
	sort.Strings(names)
	for _, rel := range names {
		p := filepath.Join(outputDir, rel)
		if err := os.WriteFile(p, []byte(files[rel]), 0o644); err != nil {
			return fmt.Errorf("写出 %s: %w", p, err)
		}
	}
	return nil
}
